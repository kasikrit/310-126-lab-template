import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.security.MessageDigest;
import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HexFormat;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

/**
 * Course run helper for 310-126 OOP (do not edit this file).
 *
 * Two steps every time, in the repo folder (same commands in Windows PowerShell and macOS Terminal):
 *   1. compile:  javac *.java                       compiles your code and Run.java into .class files
 *   2. run:      java Run HelloWorld                runs HelloWorld and records the run
 *                java Run HelloWorld 1 2 3          1 2 3 go to main(String[] args) in order
 *                java Run Greeter "Somchai Jaidee"  quote an argument that contains spaces
 *
 * Every run:
 *   1. checks that every .java file was compiled after its last change (otherwise: compile first, nothing is recorded);
 *   2. runs the compiled main class; if input.txt exists it is sent as keyboard input (otherwise input is empty);
 *   3. shows the program's output and errors on screen;
 *   4. appends one block to outputs.txt: time, command, SHA-256 of each .java file, exit code and the full output.
 * Run never runs git. Commit yourself after each run:  git add .  then  git commit -m "..."
 * Never edit outputs.txt by hand; the instructor re-runs (replays) your code and compares.
 */
public class Run {
    static final String LOG = "outputs.txt";
    static final int TIMEOUT_SECONDS = 30;

    public static void main(String[] argv) throws Exception {
        if (argv.length == 0) {
            System.out.println("Usage: javac *.java   then   java Run <MainClass> [arguments...]   e.g.  java Run HelloWorld");
            System.exit(2);
        }
        String main = argv[0].replaceAll("\\.(java|class)$", "");
        List<String> args = List.of(argv).subList(1, argv.length);
        Path root = Path.of("").toAbsolutePath();

        List<Path> sources = javaSources(root);
        if (sources.stream().noneMatch(p -> p.getFileName().toString().equals(main + ".java"))) {
            System.out.println("Run: " + main + ".java not found in " + root);
            System.out.println("Run this command inside the repo folder, e.g.  cd 310-126-lab0");
            System.exit(2);
        }
        List<String> stale = staleSources(root, sources);
        if (!stale.isEmpty()) {
            System.out.println("Run: compile first, these files changed after their last compile (or were never compiled):");
            for (String s : stale) System.out.println("  " + s);
            System.out.println("  javac *.java      then run again. Nothing was recorded in " + LOG + ".");
            System.exit(2);
        }
        Path input = root.resolve("input.txt");
        boolean hasInput = Files.isRegularFile(input);

        Path javaBin = Path.of(System.getProperty("java.home"), "bin", isWindows() ? "java.exe" : "java");
        List<String> cmd = new ArrayList<>(List.of(javaBin.toString(),
                "-Dstdout.encoding=UTF-8", "-Dstderr.encoding=UTF-8", "-cp", root.toString(), main));
        cmd.addAll(args);
        ProcessBuilder pb = new ProcessBuilder(cmd).directory(root.toFile()).redirectErrorStream(true);
        Path empty = Files.createTempFile("run310126", ".in");
        pb.redirectInput(ProcessBuilder.Redirect.from(hasInput ? input.toFile() : empty.toFile()));
        String exit;
        String output;
        try {
            Process proc = pb.start();
            ByteArrayOutputStream buf = new ByteArrayOutputStream();
            Thread pump = new Thread(() -> copy(proc.getInputStream(), buf));
            pump.start();
            if (proc.waitFor(TIMEOUT_SECONDS, TimeUnit.SECONDS)) {
                exit = Integer.toString(proc.exitValue());
            } else {
                proc.destroyForcibly();
                exit = "timeout";
            }
            pump.join(2000);
            output = buf.toString(StandardCharsets.UTF_8);
            if (exit.equals("timeout")) output += "\n[Run: stopped after " + TIMEOUT_SECONDS + " seconds]\n";
        } finally {
            Files.deleteIfExists(empty);
        }
        output = output.replace("\r\n", "\n");
        System.out.print(output);
        if (!output.isEmpty() && !output.endsWith("\n")) System.out.println();

        int n = previousRuns(root.resolve(LOG)) + 1;
        StringBuilder b = new StringBuilder();
        b.append("=== run ").append(n).append(" | ")
         .append(OffsetDateTime.now().truncatedTo(ChronoUnit.SECONDS).format(DateTimeFormatter.ISO_OFFSET_DATE_TIME))
         .append(" ===\n");
        b.append("command: java Run ").append(main);
        for (String a : args) b.append(' ').append(a.matches("[^\\s\"']+") ? a : "\"" + a.replace("\"", "\\\"") + "\"");
        b.append('\n');
        b.append("main: ").append(main).append('\n');
        b.append("args: ").append(json(args)).append('\n');
        b.append("input: ").append(hasInput ? "input.txt sha256=" + sha256(input) : "none").append('\n');
        b.append("java: ").append(System.getProperty("java.version")).append('\n');
        for (Path p : sources) {
            b.append("file: ").append(rel(root, p)).append(" sha256=").append(sha256(p)).append('\n');
        }
        b.append("exit: ").append(exit).append('\n');
        List<String> lines = output.isEmpty() ? List.of() : List.of(output.split("\n", -1));
        if (!lines.isEmpty() && lines.get(lines.size() - 1).isEmpty()) lines = lines.subList(0, lines.size() - 1);
        b.append("output-lines: ").append(lines.size()).append('\n');
        b.append("--- output ---\n");
        for (String l : lines) b.append(l).append('\n');
        b.append("=== end run ").append(n).append(" ===\n\n");
        Files.writeString(root.resolve(LOG), b.toString(), StandardCharsets.UTF_8,
                StandardOpenOption.CREATE, StandardOpenOption.APPEND);

        System.out.println("----");
        System.out.println("Run: saved run " + n + " (exit " + exit + ") to " + LOG
                + ". Now commit:  git add .  then  git commit -m \"your message\"");
    }

    /** Every .java file under the repo except Run.java, skipping hidden folders (.git) and build output. */
    static List<Path> javaSources(Path root) throws IOException {
        try (Stream<Path> s = Files.walk(root)) {
            return s.filter(p -> p.toString().endsWith(".java") && Files.isRegularFile(p))
                    .filter(p -> !rel(root, p).equals("Run.java"))
                    .filter(p -> {
                        for (Path part : root.relativize(p)) {
                            String n = part.toString();
                            if (n.startsWith(".") || n.equals("out") || n.equals("bin") || n.equals("target")) return false;
                        }
                        return true;
                    })
                    .sorted(Comparator.comparing(p -> rel(root, p)))
                    .toList();
        }
    }

    /** Sources whose .class (same folder, same name) is missing or older than the .java file. */
    static List<String> staleSources(Path root, List<Path> sources) throws IOException {
        List<String> stale = new ArrayList<>();
        for (Path src : sources) {
            String name = src.getFileName().toString();
            Path cls = src.resolveSibling(name.substring(0, name.length() - 5) + ".class");
            if (!Files.exists(cls)) {
                stale.add(rel(root, src) + "  (no .class yet)");
            } else if (Files.getLastModifiedTime(src).compareTo(Files.getLastModifiedTime(cls)) > 0) {
                stale.add(rel(root, src) + "  (changed after the last compile)");
            }
        }
        return stale;
    }

    static String rel(Path root, Path p) {
        return root.relativize(p).toString().replace('\\', '/');
    }

    /** SHA-256 of the file with Windows line endings (CRLF) turned into LF, so Windows and macOS agree. */
    static String sha256(Path p) throws Exception {
        byte[] raw = Files.readAllBytes(p);
        ByteArrayOutputStream norm = new ByteArrayOutputStream(raw.length);
        for (int i = 0; i < raw.length; i++) {
            if (raw[i] == '\r' && i + 1 < raw.length && raw[i + 1] == '\n') continue;
            norm.write(raw[i]);
        }
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(norm.toByteArray()));
    }

    static int previousRuns(Path log) throws IOException {
        if (!Files.exists(log)) return 0;
        int n = 0;
        for (String l : Files.readAllLines(log, StandardCharsets.UTF_8)) if (l.startsWith("=== run ")) n++;
        return n;
    }

    static String json(List<String> items) {
        StringBuilder b = new StringBuilder("[");
        for (int i = 0; i < items.size(); i++) {
            if (i > 0) b.append(", ");
            b.append('"');
            for (char c : items.get(i).toCharArray()) {
                switch (c) {
                    case '"' -> b.append("\\\"");
                    case '\\' -> b.append("\\\\");
                    case '\n' -> b.append("\\n");
                    case '\r' -> b.append("\\r");
                    case '\t' -> b.append("\\t");
                    default -> {
                        if (c < 0x20) b.append(String.format("\\u%04x", (int) c));
                        else b.append(c);
                    }
                }
            }
            b.append('"');
        }
        return b.append(']').toString();
    }

    static void copy(InputStream in, ByteArrayOutputStream out) {
        try (in) {
            in.transferTo(out);
        } catch (IOException ignored) {
            // process was stopped
        }
    }

    static boolean isWindows() {
        return System.getProperty("os.name").toLowerCase().contains("win");
    }
}
